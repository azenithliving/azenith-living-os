import { appendFileSync, readFileSync } from "node:fs";

const ledgerPath = "docs/ledger/council-minutes.md";
const MARK = "المواعيد في الفوتر";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));

const addition = ar(`
- **وكيل المتجر (${new Date().toISOString().slice(0, 16).replace("T", " ")}):** **${MARK}:** بعد ما الجهاز اتقفل وفُتح، المكان اتأكد منه الأول: آخر حفظ هنا = آخر حفظ على السحابة، والموقع ردّ برقم المالك في الإعدادات العامة وفي فوتر الرئيسية وفي الكتالوج، والرفّ «قريبًا». (لحظة أول فتح رجّعت «مفيش رد» من ٣ عناوين — اتقيس إن ده النت بتاع الجهاز لسه مفيق: جيت‌هَب وفيرسل نفس اللحظة ٢٠، والعناوين رجعت ٢٠٠ بعد دقيقة.)
  - **اللي كان مقفول:** machinery المواعيد موجود ومظبوط (٢٣٦ سطر يحسب وقت القاهرة، والجمعة وحدها مفيش شغل) بس **سطح واحد** للعميل كان بيقراه — نموذج النخبة. واللي بيقوله العميل عن المواعيد: **صفر** في الرئيسية و«من نحن» و«الغرف» و«تواصل معنا».
  - **اللي اتعمل:** الفوتر — اللي على كل صفحة للعميل — بقى يحمل سطر المواعيد **منفسه** من السطر اللي المالك كتبه في سجل المتجر (نفس السطر اللي المستشار بيقوله)، وكلمته عن إن ملناش معرض. ومفيش نسخة تانية للجملة: الجملة اتعلّنت مرة واحدة في ملف الحقائق، والفوتر والردود كلها بتناديها بالاسم.
  - **البرهان الحيّ على الرابط المنشور:** خمس صفحات (الرئيسية، من نحن، الغرف، تواصل معنا، الأثاث) كلها بتطبع «المواعيد: كل أيام الأسبوع من ٩ صباحًا حتى ٨ مساءً، ما عدا الجمعة.» و«ملناش معرض…» ورقم المالك؛ **صفر رقم لاتيني** في الفوتر؛ **صفر رسالة خطأ**؛ وصورة الفوتر على عرض ٣٩٠ بكسل اتبصّ عليها فعلاً.
  - **البوابات:** 155 اختبار في حزم الأرقام والحقائق أخضر · تيبشك سليم · بناء كامل · منشور · قياس حيّ
`);

appendFileSync(ledgerPath, addition, "utf8");
const text = readFileSync(ledgerPath, "utf8");
console.log(`written=${text.includes(MARK)} · lines=${text.split("\n").length}`);
