import fs from "node:fs";

/** Records the opening-hours atom in the repository ledger. Numerals are generated. */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **المواعيد اللي بتتقال للعميل رجعت لميعادك: مصدر غلط كان بيقول ١٠ لـ ٦ وبيقفل السبت والأحد.**`,
  "  - **العيب، مقاس:** صفحة التأهيل كانت بتحسب «إمتى بنفتح» من ملف عنده ساعة خاصة بيه: من ١٠ الصبح لـ ٦ المسى، وكمان بيحوّل السبت والأحد لأيام راحة — وعطلة عندك مش موجودة. وفي نفس الوقت المسترشد كان بيجاوب صح لأنه بيقرأ سطر المواعيد من سجل الدار نفسه. يعني حقيقة واحدة، ليها صاحبين، والسطح الأحدث قرأ الغلط.",
  "  - **الإصلاح:** الرقم بقى مكتوب مرة واحدة في الملف (٩ الصبح لـ ٨ المسى، والجمعة بس هي اللي بتقفل)، وكل الجمل — العربية والإنجليزي — بتتبني منه بدل ما تكرر الساعة في النص. وشيلان عدّادين: أربع دواير مراحل في كراسة الطلب كانت لسه بأرقام لاتينية.",
  "  - **الحارس:** ملف اختبار بيبصّ الميعاد على حاله: ٩ مفتوح، ٨ مقفول، الجمعة مقفولة، السبت والأحد شغالين، والجملة العربية بتطبع «الساعة ٩» بحروفه وما فيهاش ولا حرف لاتيني. وفيه تصحيح لآلة القياس عندي: كانت بتستثني أي كلمة لاتينية مكتوبة جوه زرار مباشرة — اتقفلت الفتحة دي ورجعت تقيس ١٣ عنوان كلها صفر.",
  "  - **البوابات:** ١٧٦٢ اختبار أخضر · تيبشك سليم · بناء كامل · قياس حيّ على المنشور بعد النشر: ١٣ عنوان من شاشات العميل، صفر كلمة لاتينية وصفر رقم لاتيني.",
  "  - **فاضل من نفس الجذر:** الميعاد لسه ليه مصدرين — السطر اللي كتبته في سجل الدار (بيقرأه المسترشد) والرقم في الكود (بتحسب منه الصفحات). الخطوة الجاية: السجل يبقى هو صاحب الكلمة، والكود يسأله.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2);
