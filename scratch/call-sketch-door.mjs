import { chromium } from '@playwright/test';
import speakeasy from 'speakeasy';
import sharp from 'sharp';
import fs from 'fs';
const BASE = process.argv[2] ?? 'http://localhost:3222';
const env = Object.fromEntries(fs.readFileSync('.env.local','utf8').split(/\r?\n/).filter(l=>/^[A-Z]/.test(l)&&l.includes('=')).map(l=>[l.slice(0,l.indexOf('=')),l.slice(l.indexOf('=')+1).replace(/^"|"$/g,'')]));
const svg = `<svg width="900" height="620" xmlns="http://www.w3.org/2000/svg"><rect width="900" height="620" fill="#f7f4ec"/><rect x="120" y="120" width="640" height="360" fill="none" stroke="#222" stroke-width="6"/><text x="440" y="100" font-family="Arial" font-size="46" text-anchor="middle" fill="#111">4.50</text><text x="300" y="530" font-family="Arial" font-size="46" text-anchor="middle" fill="#111">3.20</text></svg>`;
const png = await sharp(Buffer.from(svg)).png().toBuffer();
const b = await chromium.launch({ headless: true });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
await p.goto(`${BASE}/gate/login`,{waitUntil:'domcontentloaded',timeout:60000});
await p.fill('input[type=email]',env.ADMIN_GATE_EMAIL);
await p.fill('input[type=password]',env.ADMIN_GATE_PASSWORD);
await p.click('button[type=submit]');
await p.waitForSelector('input[placeholder="000000"]',{timeout:30000});
const s=env.ADMIN_GATE_2FA_SECRET.replace(/\s+/g,'').replace(/-/g,'').toUpperCase();
await p.fill('input[placeholder="000000"]',speakeasy.totp({secret:s,encoding:'base32',step:30,digits:6}));
await p.click('button[type=submit]');
for(let i=0;i<15&&!p.url().includes('/admin');i++) await p.waitForTimeout(2000);
const out = await p.evaluate(async ([b64]) => {
  const r = await fetch('/api/admin/ops/sketch', { method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({ image_base64: `data:image/png;base64,${b64}` }) });
  return { status: r.status, body: await r.text() };
}, [png.toString('base64')]);
console.log('HTTP', out.status);
console.log(out.body.slice(0, 900));
await b.close();
