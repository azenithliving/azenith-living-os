import { chromium } from "@playwright/test";
const BASE = "https://azenith-living.vercel.app";
const b = await chromium.launch({ headless: true });
const p = await (await b.newContext({ viewport: { width: 390, height: 900 }, locale: "ar-EG" })).newPage();
await p.goto(`${BASE}/rooms/living-room`, { waitUntil: "domcontentloaded", timeout: 90000 });
await p.waitForTimeout(6000);
await p.screenshot({ path: "scratch/room-name-living.png" });
console.log("h1:", await p.evaluate(() => document.querySelector("h1")?.textContent?.trim()));
await p.goto(`${BASE}/request`, { waitUntil: "domcontentloaded", timeout: 90000 });
await p.waitForTimeout(6000);
await p.getByText("شقة", { exact: true }).first().click();
await p.waitForTimeout(1500);
await p.getByText("على المحارة / طوب أحمر", { exact: true }).first().click();
await p.waitForTimeout(1500);
await p.getByText("فئة فاخرة - خامات وتفاصيل مخصصة مستوردة", { exact: true }).first().click();
await p.waitForTimeout(2500);
const step = await p.evaluate(() => document.body.innerText.includes("الفراغات") || document.body.innerText.includes("غرف المعيشة والصالات"));
console.log(" spaces visible:", step);
await p.screenshot({ path: "scratch/room-name-request-step.png" });
await b.close();
