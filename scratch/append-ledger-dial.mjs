import fs from "node:fs";

/** Records the dialable-number atom in the repository ledger. Numerals are generated. */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => String(s).replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **الرقم اللي على شاشتك بقى هو اللي بتطلبه.**`,
  "  - **العيب، مقاس من الصورة:** الملف الذهبي كان بيكتب «١٠٩٩٩٩٩٩٩١» — وده مفتاح الدفتر الداخلي اللي بيتجرّد من الصفر الأول بالقصد — وزرار «اتصل بيه» كان بيلزق +20 على أي شكل مخزّن، فاللي مسجّل بصيغته الكاملة («0100…») بيطلع «+200100…» أي رقم ما بيربطش. وفي شاشة العملاء كان الشرط بيطلب صفر في الأول، فالعميل اللي جه من ورقته بس كان بيفقد زرار الواتساب في صمت.",
  "  - **الإصلاح:** قاعدة واحدة ترجّع ثلاث صيغ من أي كتابة (اللي يقرأه المالك بالصفر الأول · اللي يطلبه +20 · اللي ياخده واتساب) وترفض أي رقم مش موبايل مصري بدل ما تدي زرار ميت. الشاشة دي بقت بتستخدمها، وشاشة العملاء فقدت نسختها الخاصة من القاعدة (اتشالت)، وسطر العميل بلا اسم بقى يطبع الرقم الكامل بدل المفتاح.",
  "  - **الدليل الحيّ على المنشور:** سطر الملف بقى «عميل من غير اسم · ٠١٠٩٩٩٩٩٩٩١ · ٣ ورقة» · الاتصال = 201099999991 بصيغة +20 · واتساب = 201099999991 · 12 رقم عربي في السطر · صفر خطأ كونسول · والصورة متبصّ عليها.",
  "  - **البوابات:** 1773 اختبار أخضر (منها 4 حالات جديدة: خمس كتابات لنفس الرقم تطلع نفس الثلاث صيغ، والرقم الناقص يرفض) · تيبشك سليم · بناء كامل.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2);
