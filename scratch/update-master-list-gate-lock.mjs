const convertedBlock = block
  .replace(/\[\[([^\]]+)\]\]/g, (_m, inner) => TICK + inner + TICK)
  .split(new RegExp(`(${TICK}[^${TICK}]*${TICK})`, "g"))
  .map((part) => (part.startsWith(TICK) ? part : ar(part)))
  .join("");

const patched = lines.join("\n") + convertedBlock;
// Only what this run writes is checked — the document's older blocks carry machine identifiers in plain
// prose, and that is their own business, not a reason to refuse today's line.
const mine = convertedBlock + "\n" + written.join("\n");
const outside = mine.replace(new RegExp(`${TICK}[^${TICK}]*${TICK}`, "g"), "").replace(/\[\[[^\]]+\]\]/g, "");
const latinWords = [...new Set([...outside.matchAll(/[A-Za-z]{3,}/g)].map((m) => m[0]))].filter(
  (w) => !["https", "http", "sql", "xx"].includes(w.toLowerCase()),
);
const latinDigits = [...outside.matchAll(/[0-9]/g)].length;
if (latinWords.length || latinDigits) {
  console.log(`REFUSING: Latin leaked — words=${latinWords.slice(0, 12).join(", ")} digits=${latinDigits}`);
  process.exit(1);
}

writeFileSync(PATH, patched, "utf8");
console.log(`written · ${patched.split(/\r?\n/).length} lines · items 33 and 18 patched, dated block appended`);
