  "  **مفتوح:** أي المحادثتين هي حسابه اللي في موبايله، عشان تنبيهات الأمان لسه بتروّح للافتراضية لوحدها (مهمة 35) · اسمين للأوضة الواحدة (34) · رد الإحصائيات الإنجليزي (32) · أبواب النموذج اللي لسه ما نزلتش لأرضية صفر المفاتيح (11).",
