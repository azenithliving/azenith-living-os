import fs from "node:fs";

/**
 * Records the customer-page language repair in the repository ledger. Numerals are generated,
 * and the script refuses to write if any Latin digit survives — the same guard as the last minute.
 */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **شاشات العميل بقت بعربيته: ٧١ سلسلة لاتينية صارت صفر، والحارس اتقفل.**`,
  "  - **تصحيح لقياس إمبارح:** الآلة الأولى كانت بتقرأ أول محطة بس. لما مشيت العناوين محطة محطة طلع اللي قبل الإصلاح: الطلب ٢٢ · البداية ٢٦ (كانت مسجّلة صفر!) · الأثاث ٢١ · الرئيسية ٢ · الغرف صفر = ٧١ سلسلة. عشان كده القياس دلوقتي بيمشي كل المحطات مش أول شاشة.",
  "  - **اللي اتصلح في مصدر الجملة:** عنوان صفحة الطلب وتسمية سبع مراحل في معاينة الكراسة · ثلاث مراحل توصيفية كانت مبنية على «Layouts و Moodboards و BOQ» · فئات الميزانية والأنماط اللي كانت بتعرّف نفسها باللاتيني · كود العملة في ٣٣ سطر سعر وميزانية بقى «جنيه» · عنوان بريدي كان بيوقّع الماركة باللاتيني · ردّ المسترشد كان بيقول «GPS» · رسالتان خطأ كانتا بيطبعوا اسم المزوّد وأمر التقليم على شاشة العميل (اتنقلوا للّوق) · مفتش آلة في رسالة فشل القارئ · رموز الإضاءة في نصائح الغرف.",
  "  - **الحارس:** ملف اختبار جديد بيمشي على ٢٠٢ ملف من سطح العميل (بره مكاتب الإدارة) وبيرفض أي سلسلة عربية جوهها كلمة لاتينية، وبيرفع الراية لو القارئ ما كملش تحليل سطر، وفيه أربع حالات سلبية بتثبت إن المحسوب مش فاضي.",
  "  - **البوابات:** ١٧٥١ اختبار أخضر · تيبشك سليم · بناء كامل · قياس حيّ على المنشور بعد النشر: الطلب صفر · البداية صفر · الأثاث صفر · الرئيسية صفر · الغرف صفر · العنوانان (الطلب والحجز) ١٤٠٣ حرف زي ما كانت، يعني النص اتترجم ما نقصش.",
  "  - **اللي لسه مفتوح من نفس الباب:** الأرقام اللاتينية في الأسعار على شاشات العميل (٢٥,٠٠٠ بدل ٢٥٠٠٠) — البند ده قرار مالك مش رقع، وبيمس كل الكتالوج.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2);
