import { appendFileSync } from "node:fs";

/** The internal-door census: what was measured, and the two defects it found instead. */
const ar = (text) => text.replace(/[0-9]/g, (d) => String.fromCharCode(0x660 + Number(d)));
const now = new Date();
const stamp = ar(
  `${now.getUTCFullYear()}-${String(now.getUTCMonth() + 1).padStart(2, "0")}-${String(now.getUTCDate())
    .padStart(2, "0")} ${String(now.getUTCHours()).padStart(2, "0")}:${String(now.getUTCMinutes()).padStart(2, "0")}`
);

const minute = `

- **وكيل المتجر (${stamp}):** **جرد الأبواب الداخلية التسعة اللي بتكلم الموديل: ولا واحد فيهم واقع من غير أرضية — وطلع بدلها عيبان تانيان.**
  - **المنهج:** قرأت فرع الفشل في كل باب، مش استنتاج من إنه «بيكلم الموديل على طول» — نفس الغلط اللي وقعت فيه امبارح في باب المستشار واتقاس وعُدّل.
  - **النتيجة، باب باب:** موجّه النوايا — قواعد أول ثم موديل، والفشل يرجّع «لا شيء» · مصنّف النوايا — الفشل يرجّع تصنيفًا قاعديًا «كلام عادي» · العقل السيادي — الفشل برجّع فكرة عربية ومقترحات محسوبة من المشاهدات · الناقد — الفشل بيرجّع الردّ كما هو، فهو تلميع مش بوابة · الرقابة الذاتية — الرقم اللي مش مقاس يرجّع «لا شيء» مش صفر · المزودات المتخصصة — كل فشل «لا شيء» · محرك الدستور — أصلاً مفيش موديل في طريقه، قواعد بس (قايمتي كانت غلط) · وكيل طليعة — كلامه فعلة آلة، بس مفيش ولا سطح بينادي عليه (سجل الدمج مسجّله كده من قبل) · الحارس — بيردّ، بس نص تنبيهاته إنجليزي.
  - **العيب الأول اللي اتفتح:** تنبيهات الحارس بتوصلشاشته بالإنجليزي («مفتاح قد يكون مقيدًا…» بالعربي يعني)، وفيها نص استثناء راكب في الجملة («خطأ من واجهة خارجية: <رسالة الخطف>») — وصحة الإدارة بتقرا الباب ده وتعرضها. القانون بيتكسر مرتين: عربيته، وإن الاستثناء مكانه اللوج. اتسجّل خطوة مستقلة، والإصلاح في مصدر الجُلة مش ترجمة وقت العرض.
  - **العيب التاني (صغير، في نفس الخطوة):** مصنّف النوايا بيحط في خانة «السبب» كلمة آلة («بديل الموجّه») واللوحة السيادية بتطبع السبب — فممكن يبان على كارت.
  - **الرقم ده اتقال من قياس، مش انطباع:** ٩ أبواب، ٠ فجوة أرضية، ٢ عيب تاني اتفتحوا، و١ من القايمة اتشال لأنها أصلاً مش باب موديل.
`;

appendFileSync("docs/ledger/council-minutes.md", ar(minute), "utf8");
console.log("appended");
