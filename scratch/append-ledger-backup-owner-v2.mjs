import { appendFileSync, readFileSync } from "node:fs";

const LEDGER = "docs/ledger/council-minutes.md";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));
const BT = String.fromCharCode(96);

const raw = `

- **الوكيل (2026-10-19 17:55):** **النسخة الاحتياطية كان لها صاحبة تانية في الشات — كانت وهمية، واتوحّد المصدر.** محاجة النهاردة كانت بتثبت إن أداة «اعمل نسخة احتياطية» بقت تنادي الوحدة اللي اتقاست، فاتضح إن الباب الموحّد للأدوات بيرفض قبل ما ينفّذ أي أداة: بيكتب أول سطر في جدول مش موجود في السجل. **النص المقياس على الرابط المنشور:** @@BT@@Failed to create execution record: Could not find the table 'agent_executions'@@BT@@ — يعني ولا أداة شات تقدر تنفّذ من الباب ده النهاردة، وده عيب سابق على شغل الليلة، اتكتب هنا عشان ما ينسبش لها.
  - **اللي اتصلح في الشغل ده (٣ كوميتات):** الأداة والعدّاد بيقرا من نفس الوحدة المقيسة، ولوحة الصحة بقت تقرا قِدَم النسخة من الختم بدل الجدول الميت، وباب الرجوع بيسمّي النسخ الموجودة بدل ما يقول «مفيش»، والحلقة اللي كانت بتطلب عنوان تحميل **عام** لبيانات المالك اتشالت، والمقابض اللي الأداة بتعلنها وما بتنّفذش (قائمة جداول، فترة احتفاظ، تضمين ملفات) اتشالت من العقد — يعني مفيش مقبض بيخبط هوا. **سبعة حرّاس** للوحدة دي.
  - **اللي ما اتعملش:** ملف إنشاء الجدول الناقص موجود في المستودع من غير ما يتطبّق، بس بيخلق خمس طاولات منها الطاولة اللي بيقراها صفحة معاينة الأقسام — ودي قراره هو. فالمهمة 118 واقفة مستنية كلمته، ومفيش جدول اتعمل ولا اتحذف الليلة.
  - **البوابات:** 2,253 اختبار أخضر · تيبشك سليم · بناء كامل · منشور · **النسخة نفسها مقاسة حيًّا 40 من 40 على الرابط المنشور** من المسار اللي مش موقوف (باب الجدولة) · كابينة المالك على عرض 390: 6 من 6 بصفر رسالة خطأ وصورة اتبصّ عليها.
`;

const text = ar(raw).replace(/@@BT@@/g, BT);
const outside = text.split(BT).filter((_v, i) => i % 2 === 0).join("");
const latin = [...new Set(outside.match(/[A-Za-z]{2,}/g) ?? [])];
if (latin.length) {
  console.error("مرفوض: لاتيني بره كود:", latin.slice(0, 10).join(", "));
  process.exit(1);
}
const foreign = text.match(/[　-ヿ㐀-䶿一-鿿가-힯豈-﫿֐-׿]/g);
if (foreign) {
  console.error("مرفوض: حرف مش عربي تسرّب");
  process.exit(1);
}
const before = readFileSync(LEDGER, "utf8");
appendFileSync(LEDGER, text);
const added = readFileSync(LEDGER, "utf8").slice(before.length);
console.log(`السجل: +${added.trimEnd().split("\n").length} سطر`);
