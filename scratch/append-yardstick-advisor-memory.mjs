import { readFileSync, writeFileSync } from "node:fs";

const FILE = "D:/alaa2/الشركة الجديدة/القائمة الجامعة - مسار الوصول للشكل النهائي.md";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));

const itemOld =
  "**اللي لسه ناقص في نفس البند:** المتجهات — الذاكرة دلوقتي نصّية بتشتغل بصفر مفتاح نموذج، والبحث بالمعنى (`pgvector`) ما اتعملش؛ وذاكرة السرب المتجهية لسه **صفر سطر** بقارئ حيّ ومنبع ميت.";
const itemNew =
  "**والمسترشد بقى يفتكره:** أول ما يكتب رقمه في كلامه، أول سطر في الرد هو اللي الدار عارفه قبل المحادثة دي — «الدار فاكر: طرازه مودرن · منطقته التجمع · غرفته صالة معيشة» — **والجملة بتتكتب في الباب نفسه مش من الموديل**، فمفتاح نموذج بايظ ما يسرقهاش (مقاس حيّ: ١٢ من ١٢ قياس، صورة اتبصّ عليها، والسالب: رقم تاني من غير تاريخ = ولا جملة). وكلامه في المحادثة بيرجع يتسجل تحت رقمه. **اللي لسه ناقص في نفس البند:** المتجهات — الذاكرة دلوقتي نصّية بتشتغل بصفر مفتاح نموذج، والبحث بالمعنى (`pgvector`) ما اتعملش؛ وذاكرة السرب المتجهية لسه **صفر سطر** بقارئ حيّ ومنبع ميت؛ والجملة العربية بتتقال لجلسة عربية (الإنجليزي بياخدها في البرومبت بس).";

const block = ar(`

- **المسترشد بيجاوب من ذاكرة الدار (نفس اليوم، بالليل):** البند ١٧ (المسترشد) و ١٩ (ذاكرة العميل) اتقاسوا مع بعض على الرابط المنشور: عميل راجع يكتب رقمه → الرد يفتتح بـ **«الدار فاكر: طرازه مودرن · منطقته التجمع · غرفته صالة معيشة»** قبل جملة التأكيد، **من غير موديل** (الجملة بتتكتب في الباب، لأن الباب أصلًا بيمسح ردّ الموديل لما العميل يكتب رقم — فلو الذاكرة اتقالت للموديل بس، عميل راجع ما كانسمعهاش). **١٢ قياس · نجح ١٢ · فشل ٠** على عرض ٣٩٠ بكسل بصور اتبصّ عليها، والسالب متقاس (رقم من غير تاريخ = ولا جملة، ولا سطر)، والجدول رجع **صفر** بعد ما اتمسح. **عيبان في الكتابة القديمة اتصلحوا في نفس اللافة:** استمارة النخبة كانت بتدّعي مصدر «كلام مع المسترشد» لإجابات الاستمارة، وبتنسخ الطراز زي ما العمود بيقوله (والعمود فيه **١٤ سطر** باسم الشاشة [[elite-brief]] و **٢** بـ [[مودرن (Modern)]] و **١** بمفتاح إنجليزي) — بقى المصدر باسمه الحقيقي والطراز يعدي على قارئ الدار، والسطح ما يطبعش قيمة لسه لابسة لاتيني. **والجدول الميت** (٣ أعمدة، ٠ سطر، كتابة بستة أعمدة مش موجودة) اتشال من طريق المسترشد نهائيًا. **العدد ما اتغيّرش:** البندان كانوا مُثبتين بدليل قبل كده، واللافة دي وسّعت القدرة مش فتحت بند جديد. اللي لسه ناقص: قياس حيّ لإصلاح الاستمارة (محروس باختبار على قيم مقاسة بس)، وقاع «بلا مفاتيح» محروس باختبار مش بانقطاع متعمَّد في الإنتاج.
`);

const source = readFileSync(FILE, "utf8");
if (!source.includes(itemOld)) {
  console.error("مرفوض: سطر الناقص في البند ١٩ اتغيّر — القراءة تقف مش الكتابة");
  process.exit(1);
}
const out = source.replace(itemOld, ar(itemNew)) + block;

const outside = out.replace(/\([^)]*\)/g, "").replace(/`[^`]*`/g, "").replace(block.replace(/`[^`]*`/g, ""), "");
const leaks = (out.match(/[A-Za-z]{3,}/g) ?? []).filter((w) => !["pgvector", "elite", "brief", "Modern", "users", "requests", "events"].includes(w));
const cjk = out.match(/[一-鿿]/g);
if (cjk) {
  console.error("مرفوض: حرف صيني تسرّب:", cjk.slice(0, 5).join(" "));
  process.exit(1);
}
if (leaks.length) console.log("تنبيه: كلمات لاتينية (مقبولة جوه اسم ملف/جدول بس):", [...new Set(leaks)].slice(0, 8).join(", "));

writeFileSync(FILE, out);
console.log(`القائمة: ${source.length} → ${out.length} حرف · سطر الناقص اتحدّث: ${out.includes("والمسترشد بقى يفتكره")}`);
console.log("البلوك المضاف فيه أرقام عربية:", /[٠-٩]/.test(block));
