import { appendFileSync, readFileSync } from "node:fs";

const LEDGER = "docs/ledger/council-minutes.md";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));
const BT = String.fromCharCode(96);
const FOREIGN = new RegExp("[\\u3000-\\u30ff\\u3400-\\u4dbf\\u4e00-\\u9fff\\uac00-\\ud7af\\uf900-\\ufaff\\u0590-\\u05ff]");

const raw = `

- **الوكيل (2026-10-19 21:25):** **الإتاحة اتقاست على كل شاشات الإدارة: ٣٠ شاشة، مش ست.** المسح على الرابط المنشور بعرض ٣٩٠ بكسل، كل شاشة في سياقها: **صفر شاشة ما فتحتش، ١٥ عقدا مخالفا في ٦ قواعد، كلها في اللوحة القديمة** (الصفحة الرئيسية القديمة ومساعدها والنخبة والمصير والصندوق والإعدادات) — ودي المتجمّدة بكلمته من قبل، مش مطلوب إصلاحها قبل استيعاب كل ذرّة. **اللوحة الجديدة كلها: صفر مخالفة وصفر خطأ كونسول.**
  - **اللي الآلة ما حكمتش عليه (١٦ عقدا) اتعدّى عليه بإيد مش باتفاق:** مقياس جديد بيوصّل العقدة قدام العدسة، بيخفي نصها ونص كل اللي جواها، بيصوّر الخلفية المتدرّجة لوحدها، وبيحسب تباين حرف على كل بكسل وياخده أسوأ بكسل. **النتيجة: موضعين مقبولين — ٩٫٠٠ و ٥٫٨٢ مقابل المطلوب ٤٫٥.**
  - **و ٨ مواضع المقياس رفض يحكم عليها** لأن الصورة اللي جت ما فيهاش حروف أصلًا — إطار الأب مش شامل النص اللي بيفرّعه. ده عيب في مقياسي أنا، فاتسجّل مهمة (١٢٠) ومش محسوب سلامة ولا فشل. **الحكم بالسلامة على حاجة متقاستش هو نفس المرض اللي بنطرد منه في كل حتة تانية.**
  - **عيبين في المقياس نفسه اتكشفوا وإتنصلحوا قبل أي رقم:** الأول كان بيحسب لون النص من نص كلام مثل @@BT@@oklab(...)@@BT@@ بالبحث عن الأرقام، فطلع تباين ١٫٠٠ لحتة سليمة؛ والتاني كان بيصوّر منطقة بره الشاشة (بياض) فحسبه فشلا. اللون بقى بيتحلّ برسمه على كانفاس، والمنطقة بتيجي بعد تمرير العقدة قدام العدسة.
  - **البوابات:** 2,257 اختبار أخضر · تيبشك سليم · بناء كامل · منشور · مقياس حيّ: مسح ٣٠ شاشة + مقياس التباين اليدوي.
`;

const text = ar(raw).replace(/@@BT@@/g, BT);
const outside = text.split(BT).filter((_v, i) => i % 2 === 0).join("");
const latin = [...new Set(outside.match(/[A-Za-z]{2,}/g) ?? [])];
if (latin.length) {
  console.error("مرفوض: لاتيني بره كود:", latin.slice(0, 10).join(", "));
  process.exit(1);
}
if (FOREIGN.test(text)) {
  console.error("مرفوض: حرف مش عربي تسرّب");
  process.exit(1);
}
const before = readFileSync(LEDGER, "utf8");
appendFileSync(LEDGER, text);
const added = readFileSync(LEDGER, "utf8").slice(before.length);
console.log(`السجل: +${added.trimEnd().split("\n").length} سطر`);
