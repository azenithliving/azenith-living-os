import { chromium } from "@playwright/test";
import { readFileSync } from "node:fs";
import speakeasy from "speakeasy";
const BASE = "https://azenith-living.vercel.app";
const env = Object.fromEntries(readFileSync(".env.local","utf8").split(/\r?\n/).filter(l=>/^[A-Z0-9_]+=/.test(l)).map(l=>[l.slice(0,l.indexOf("=")),l.slice(l.indexOf("=")+1).trim().replace(/^["']|["']$/g,"")]));
const b = await chromium.launch({ headless: true });
const p = await (await b.newContext({ viewport:{width:390,height:900}, locale:"ar-EG" })).newPage();
await p.goto(`${BASE}/gate/login`, { waitUntil:"domcontentloaded", timeout:90000 });
await p.waitForTimeout(4000);
await p.fill("input[type=email]", env.ADMIN_GATE_EMAIL);
await p.fill("input[type=password]", env.ADMIN_GATE_PASSWORD);
await p.click("button[type=submit]");
await p.waitForSelector('input[placeholder="000000"]', { timeout:40000 });
const secret = env.ADMIN_GATE_2FA_SECRET.replace(/\s+/g,"").replace(/-/g,"").toUpperCase();
await p.fill('input[placeholder="000000"]', speakeasy.totp({secret, encoding:"base32", step:30, digits:6}));
await p.click("button[type=submit]");
for (let i=0;i<20 && !p.url().includes("/admin"); i++) await p.waitForTimeout(2000);
await p.goto(`${BASE}/admin/v2/agents/ops`, { waitUntil:"domcontentloaded", timeout:90000 });
await p.waitForTimeout(15000);
const seen = await p.evaluate(() => {
  const bubbles = [...document.querySelectorAll("div")].filter(d => d.className && String(d.className).includes("rounded-2xl"));
  const text = bubbles.map(b => b.innerText).join("\n");
  const latin = text.match(/(?<![A-Za-z0-9./_-])[0-9]+(?![A-Za-z0-9./_-])/g) ?? [];
  const anyLatin = text.match(/[0-9]/g) ?? [];
  const sample = (text.match(/.{0,30}[0-9].{0,20}/) ?? [""])[0];
  return { bubbles: bubbles.length, anyLatin: anyLatin.length, standalone: latin.length, sample: sample.replace(/\s+/g," ") };
});
console.log(`فُقاقيع: ${seen.bubbles} · أرقام لاتينية في النص المعروض: ${seen.anyLatin} · منها واقعة لوحدها: ${seen.standalone}`);
console.log(`عينة: «${seen.sample}»`);
await b.close();
