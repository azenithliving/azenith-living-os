import { appendFileSync, readFileSync } from "node:fs";

/** Ledger minute for the two load-sensitive guards (#40 and #57). Digits converted by `ar()`. */
const ar = (text) => text.replace(/[0-9]/g, (d) => String.fromCharCode(0x660 + Number(d)));

const now = new Date();
const stamp = `${now.getUTCFullYear()}-${String(now.getUTCMonth() + 1).padStart(2, "0")}-${String(
  now.getUTCDate()
).padStart(2, "0")} ${String(now.getUTCHours()).padStart(2, "0")}:${String(now.getUTCMinutes()).padStart(2, "0")}`;

const minute = `

- **وكيل المتجر (${ar(stamp)}):** **حارسين كانو بيقيسوا زحمة الماشينة مش بيقيسوا الشغل — اتقفل مصدر الشبكة واتنقل تحميل الملفات لمكانه.**
  - **العيب الأول (اختبار الموظف اللي بيقاوم العطل):** كان بيسأل «الموظف بيرجّع كلام عام عن عطل بدل ما يحوّل الطلب للوكلاء؟» — بس كان بيمرّ من نفس الطريق اللي بيبعت طلب بحث في متصفح خارجي. مقاس: ٨٫٠ ثانية في العزلة، و٣٠ ثانية (المهلة كلها) جوه تشغيل الشبكة الكامل — يعني الحكم كان «مين ردّ وإمتى» مش «السلوك صح ولا غلط». المصدر اتقفل (طبقة المتصفح بترجّع «مفيش» في الاختبار)، ونزلت العزلة لـ ٠٫٨ ثانية.
  - **العيب التاني (حارس التوثيق):** كان ماسك مهلة ١٥ ثانية عشان يخلّص من تقليم شجرة الملفات اللي بتيجي مع الباب — مش عشان الادّعاء نفسه بطيء. مقاس: ٥٦ مللي في العزلة و١٧٣–٢٢٩ مللي جوه تشغيل كامل. التقليم اتنقل لسط التجهيز (قبل كل اختبار)، والمهلة نزلت ٣ ثانية، وراحت حديدة اختبارات: أي نداء شبكة يرجع في الطريق ده يفشل الحارس بدل ما يختبي ورا مهلة طويلة — والحارس لسه بيرفض النداء من غير دخول بـ٤٠١.
  - **قرار مقصود:** ما وسّعناش المهل. الاختبار اللي شغله ٥ ثواني تحت الحمل كان بيقول إن «تحميل الملفات» هو البطيء، فالاتنين بقو يقيسوا الجواب بس، والتحميل اتحسب في التجهيز بمهلة كبيرة صريحة.
  - **البوابات:** ١٩٢٤ اختبار أخضر · تيبشك سليم · بناء كامل · **تشغيلان كاملان متتاليان** (٤٫٠ و ٤٫٢ ثانية للملف ده تحت الزحمة، و١٢٩ و ٢٣٠ مللي لحارس التوثيق) — ده معيار الذرّة نفسها.
  - **الفرق اللي لازم يتقال:** الذرّة دي محروسة باختباراتها نفسها مش بدليل حيّ على الرابط المنشور — مفيش شاشة اتغيّرت، اللي اتغيّر هو آلة الاختبار.
`;

appendFileSync("docs/ledger/council-minutes.md", ar(minute), "utf8");
const written = readFileSync("docs/ledger/council-minutes.md", "utf8");
console.log(`append: +${ar(minute).length} chars · file now ${written.length} chars`);
console.log("tail:\n" + written.split("\n").slice(-2).join("\n"));
