import fs from "node:fs";
import dotenv from "dotenv";
import postgres from "postgres";
for (const f of [".env.local", ".env"]) if (fs.existsSync(f)) dotenv.config({ path: f });
const sql = postgres(process.env.DIRECT_URL, { max: 1 });
const r = await sql`select tablename from pg_publication_tables where pubname = 'supabase_realtime' order by tablename`;
console.log("PUBLISHED=" + r.length + " :: " + r.map((x) => x.tablename).join(","));
const pubs = await sql`select pubname from pg_publication`;
console.log("PUBLICATIONS=" + pubs.map((x) => x.pubname).join(","));
const rep = await sql`select relname, relreplident from pg_class where relname in ('agent_events','ops_sync_events')`;
console.log(rep.map((x) => x.relname + "=" + x.relreplident).join(","));
await sql.end();
