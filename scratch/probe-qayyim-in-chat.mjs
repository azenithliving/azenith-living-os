import { createClient } from "@supabase/supabase-js";
import dotenv from "dotenv";
dotenv.config({ path: ".env.local" });
const sb = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
const { data, error } = await sb.from("agent_messages").select("sender_name,content,created_at").eq("sender_type","agent").like("content","%qayyim%").order("created_at",{ascending:false}).limit(400);
if (error) throw new Error(error.message);
console.log(`rows carrying the retired key: ${data.length} (read cap is 1000, so this may be the cap)`);
const shapes = new Map();
for (const r of data) for (const m of String(r.content).match(/[A-Za-z_]*qayyim[A-Za-z_]*/gi) ?? []) shapes.set(m, (shapes.get(m) ?? 0) + 1);
[...shapes.entries()].sort((a,b)=>b[1]-a[1]).slice(0,12).forEach(([w,n])=>console.log(`  ${w}: ${n}`));
