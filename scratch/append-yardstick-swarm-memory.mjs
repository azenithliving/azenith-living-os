import { readFileSync, writeFileSync } from "node:fs";

const FILE = "D:/alaa2/الشركة الجديدة/القائمة الجامعة - مسار الوصول للشكل النهائي.md";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));

const oldPhrase = "وذاكرة السرب المتجهية لسه **صفر سطر** بقارئ حيّ ومنبع ميت";
const newPhrase =
  "وذاكرة السرب بقت بتتكتب: الجولة اليومية بتنزل اللي قاسته فعلًا في سجل الموظفين (مقاس حيّ على المنشور: 4 سطور، كلها عليها متجه حقيقي)، والرد بقى يقول على وش المالك **«رجع لذاكرة الدار»** — بالكلمة لما مفيش مفتاح نموذج، وبدل ما يرجع نص فاضي زي الأول";

const block = ar(`

- **ذاكرة السرب لقت مصدرها (نفس اليوم، بالليل):** البند 19 اتوسّع — القارئ اللي كان شغال على كل ردّ في شات المالك و**صفر سطر** وراه بقى وراه كتابة من الجولة اليومية، و**قاع صفر مفتاح**: لو البحث الدلالي ما ردّش، الذاكرة بتترجع بكلمة العربية نفسها، والرد بيعلن «رجع لذاكرة الدار: كم سطر ومنين». **مقاس حيّ على المنشور:** 4 سطور كتبتها الجولة (عليها متجه حقيقي) · صندوق الكلام على مكتب المدير رجع جوه الشاشة عند عرض 390 (كان بره الشاشة من شهر: 581 بكسل أزرار في 390، والصندوق ما يقدرش يقل) · والرد طلع فيه سطر الذاكرة **بالكلمة**. **الفاضي في البند:** الاختبار السالب ما اتقاسش على ردّ وصل فعلًا (الكابينة بتقطع بعد 45 ثانية)، و**بابان بيعدّوا على جدول متجهات مش موجود** (بند 111 لسه مفتوح).
- **خسارة لازم تتحسب (نفس اليوم):** آلة قياس كانت بتمسح محاجة **بمفتاح المحادثة**، فمسحت **306 سطر من تاريخ شات المالك مع الموظفين** (الجدول نزل من 1,741 لـ 1,435) — ومفيش نسخة رجوع على الخطة دي. الآلة اتعيدت كتابتها تمسح بنصّها هي وبوقتها هي بس، والحرس بقى يمنع أي حذف بمفتاح محادثة. **الباقي مقاس سليم:** 1,435 سطر في 10 محادثات، وصفر سطر يتيم.
`);

const source = readFileSync(FILE, "utf8");
if (!source.includes(oldPhrase)) {
  console.error("مرفوض: عبارة البند 19 اتغيّرت — القراءة تقف مش الكتابة");
  process.exit(1);
}
const out = source.replace(oldPhrase, ar(newPhrase)) + block;
if (/[一-鿿]/.test(out.slice(source.length - 4000))) {
  console.error("مرفوض: حرف صيني تسرّب في المضاف");
  process.exit(1);
}
writeFileSync(FILE, out);
const added = out.slice(source.length);
console.log(`القائمة: ${source.length} → ${out.length} حرف · المضاف فيه أرقام عربية: ${/[٠-٩]/.test(added)} · لاتيني بره الكود: ${(added.match(/[A-Za-z]{3,}/g) ?? []).length}`);
