import fs from "node:fs";

/** Records the single-owner schedule atom in the repository ledger. Numerals are generated. */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => String(s).replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **الميعاد بقى له صاحب واحد: الشاشة سألت سجل الدار بدل ما تكرّر رقمها.**`,
  "  - **الجذر الحقيقي، واللي طلع أعمق من إمبارح:** سجل الدار نفسه فيه سطرين متضاربين عن الميعاد. السطر الجديد اللي بيقراه المسترشد: «كل أيام الأسبوع من ٩ صباحًا حتى ٨ مساءً، ما عدا الجمعة». وسطر أقدم بنفس الجدول، مكتوب في صيغة سؤال وجواب: «الشركة فى مدينة السلام - القاهرة، ومواعيد العمل يوميا من ١٠ صباحا حتى ٦ مساء عدا يوم الجمعة». يعني الرقم الغلط ما كانش من اختراع الكود بس — كان نسخة قديمة من كلامك إنت، والكود كان بيرددها.",
  "  - **اللي اتعمل:** قارئ واحد لسطر الميعاد (المسترشد والباب العام بياخدوا منه) · آلة واحدة تحوّل الجملة لجدول ساعات، وترفض بدل ما تخمن: رقم من غير «صباح/مساء» أو ميعاد يقفل قبل ما يفتح = لا إجابة، والصفعة ترجع للرقم المأمور · الباب العام بقى يوصّل الجملة لكل الصفحات اللي بتحسب · وصحفة التأهيل والصفحة المتميزة يسألوا الباب ويبنوا حسابهم على ردّه.",
  "  - **الدليل الحيّ على المنشور:** الباب ردّ بجملة ميعادك حرفياً · والصفحة نادت على الباب مرّتين والاتنين رجعوا 200 · صفر خطأ كونسول · صفر كلمة لاتينية ظاهرة.",
  "  - **البوابات:** ١٧٦٨ اختبار أخضر (منها ١٠ على الميعاد: قارئ الجملة بقراء السطرين الحقيقيين وبيرفض المخالف، والحساب بيطيع للسجل لو قال «ما عدا السبت» وقال السبت يوم شغل لو ما قالش) · تيبشك سليم · بناء كامل.",
  "  - **اللي لسه مفتوح ومحتاج كلمة صريحة:** السطر القديم اللي بيقول 10 لـ 6 لسه موجود في السجل — ما اتحذفش لأن الحذف في القاعدة أمرك إنت. دلوقتي المسترشد والشاشة بيقرا السطر الأحدث، فالسجل ما بقاش بيخيّض بعضه، بس يفضل تضارب لو كتبته إنت تاني. وكمان عنوان الدار (مدينة السلام) عايش في نفس السطر القديم اللي قارئ المواعيد ما بيوصلوش — يعني الدار بيعرف مكانه بس مفيش شاشة بتسأله.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2);
