import { appendFileSync, readFileSync } from "node:fs";

/**
 * The ledger line for the sales office that learned to say «the record did not answer».
 */

const TICK = String.fromCharCode(96);
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));

const body = `

- **وكيل المتجر (2026-10-15 07:40):** **المكتب اللي اتعلم يقول «السجل ما ردّش»:** دي المهمة القديمة اللي كانت بتقول «محادثة المبيعات مرة جت فاضية والكونسول بس عرف» — النهاردة اتقاست على مسرحها الحقيقي واتصلحت من جذرها.
  - **القياس (3 مرات على نفس الشاشة، دخول كامل، عرض 390 بكسل، الرابط المنشور):** الباب راد → الفقاعات موجودة وصفر خطأ · الباب متقطوع في النص → الشاشة عرضت لوحة «ابدأ محادثة تشغيلية» فوق محادثة **فيها سطور فعلية**، يعني المتجر قال للمالك «مفيش جديد» وهو مقفول عن كلام موجود، و **26 رسالة خطأ في الكونسول** كانت الشاهد الوحيد · الباب راد بردّه الأمين (500 «خطأ في السيرفر») → نفس الكدبة بالظبط.
  - **الجذر (مش العَرَض):** قراءة المحادثة ما كانش لها حالة فشل خالص — [[if (data.success && …)]] من غير [[else]]، و [[catch]] بيكتب في الكونسول بس، و [[loading]] بتطفي في [[finally]] ← الرسم بيقع على لوحة «مفيش كلام». الباب نفسه كان أمينًا، بس أمانه ما كانش بيوصل للشاشة. **ده نفس عائلة العيب اللي اتقفلت في الدفتر وفي ورق المقاسات:** «اللي ما اتقراش» بيتقال بلفظ «فاضي».
  - **اللي اتعمل:** القراءة بقت تحمل حالتها: راد / فاضي فعلاً / مرفوض — و «مرفوض» بتطبع سطر عربي «المحادثة ما جاتش — السجل ما ردّش، ومش معناه إن مفيش كلام» + سبب الباب + زرار «حاول تاني»، **والفقاعات اللي على الشاشة ما بتتمسحش** لما تحديث يفشل. وفي الباب: البحث عن اسم المحادثة كان بيرمي خطأه ويجاوب «نجح ومفيش رسائل» — بقى يرفض بجملة؛ وفرع «الهيكل مش موجود» كان بيردّ «نجح» مع ملاحظة إنجليزي ما بيقراهاش ولا سطح — بقى رفض صريح.
  - **الحرس:** [[tests/admin/chatReadSpeaks.test.ts]] — 9 قياسات على الملف نفسه (حالة القراءة، والمقبض اللي بيقراه القياس الحيّ، وإن لوحة «مفيش كلام» متوصلش لحالة رفض، والعربية اللي بتطبع، وإن الفقاعات ما تروحش، ومفيش كلمة مكينة للمالك، وإن الباب ما يقولش «نجح» على قراءة مقفولة). حارس الإتاحة كشف سطر جديد محطوط بدرجة بهتان غلط واترفع لـ 70٪.
  - **البوابات:** 2,179 اختبار أخضر (كانت 2,170 الصبح) · تيبشك سليم · بناء كامل · منشور · قياس حيّ على الرابط المنشور بصور اتبصّ عليها
`;

const converted = body
  .replace(/\[\[([^\]]+)\]\]/g, (_m, inner) => TICK + inner + TICK)
  .split(new RegExp(`(${TICK}[^${TICK}]*${TICK})`, "g"))
  .map((part) => (part.startsWith(TICK) ? part : ar(part)))
  .join("");

const outside = converted.replace(new RegExp(`${TICK}[^${TICK}]*${TICK}`, "g"), "");
const latinWords = [...new Set([...outside.matchAll(/[A-Za-z]{3,}/g)].map((m) => m[0]))];
const latinDigits = [...outside.matchAll(/[0-9]/g)].length;
if (latinWords.length || latinDigits) {
  console.log(`REFUSING: Latin leaked — words=${latinWords.slice(0, 14).join(", ")} digits=${latinDigits}`);
  process.exit(1);
}

appendFileSync("docs/ledger/council-minutes.md", converted, "utf8");
console.log(`appended · ${converted.length} chars`);
