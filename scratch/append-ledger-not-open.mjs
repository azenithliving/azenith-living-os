import { appendFileSync, readFileSync } from "node:fs";

const ledgerPath = "docs/ledger/council-minutes.md";
const MARK = "المحل لسه مقفول";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));

const addition = ar(`
- **وكيل المتجر (${new Date().toISOString().slice(0, 16).replace("T", " ")}):** **${MARK}:** المالك قال كلمة بتغيّر ترتيب الشغل، واتسجّلت زي ما هي: هو **ما بيستخدمش اللوحة القديمة ومش هيكشف عليها**، و**مش هيستخدم الكابينة الجديدة هي كمان** لحد ما يكتمل كل حاجة بمية المية، والواجهة اللي بيشوفها الزائر **ما جاباش زائر حقيقي واحد من يومها** — كل اللي فيها كان هو بيختبر. وسؤال «ليه مفيش زوار؟» قاله صريح: مش شاغلنه دلوقتي ومفيش داعي لحلّه غير لما كل حاجة تبقى مكتملة وحقيقية وسليمة.
  - **اللي اتسجل كمرجع للمرات الجاية (مفيش فيه ولا سطر كود اتلمس):** الخمسطاشر عقدة الوصول اللي في البيت القديم **تجمّدت بكلمته هو**، مش بحجة إن هتتمسح — يعني أي طلب تجميل شاشة مالك لازم يتقيّم بقدر ما يقرّب من مية المية في القائمة الجامعة، مش بقول «هتشوفه إنت لما تستخدمها». والأرقام اللي جاية من تحليلات المتجر والتجارب والسجل بت تُعدّ **جلسات اختباره هو**، مش سلوك عملاء — فلا يُبنى عليها قدرة نمو ولا يُقتبس منها رقم على إنه زبون.
  - **اللي بيتغيّر في الترتيب:** الذرات تتوجّه للسطح اللي أول زائر حقيقي هيبصّ عليه (واجهة العميل: صور المنتجات، الأوصاف، مسار الطلب) وللقائمة الجامعة، بدل الصقل على شاشات مقفولة.
  - **البوابات:** مفيش — دي لافة سجل بتسجّل كلمة مالك وقرار ترتيب، وما اتغيّرش فيها سلوك ولا اختبار.
`);

appendFileSync(ledgerPath, addition, "utf8");
const text = readFileSync(ledgerPath, "utf8");
const occurrences = text.split(MARK).length - 1;
console.log(`written=${text.includes(MARK)} · MARK count=${occurrences} · ledger lines=${text.split("\n").length}`);
