import { appendFileSync, readFileSync } from "node:fs";

const ledgerPath = "docs/ledger/council-minutes.md";
const MARK = "صاحب الرقم";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));

const addition = ar(`
- **وكيل المتجر (${new Date().toISOString().slice(0, 16).replace("T", " ")}):** **${MARK}:** حصر قبل الكود، والرقم طلع ليه أربعة منبع ومش متفقين. **القياس:** جدول الإعدادات ما فيهوش خانة للمواعيد ولا للواتساب (صفر). الجدول اللي فيه الرقم فعلاً هو سجل الشركة: سطر واحد، 12 رقم بينتهي في 9584. متغيّر البيئة على السيرفر بيقول نفس الرقم (9584). بس كود «المستأجر» في lib/tenant.ts بيستعلم على جدول **مش موجود أصلاً** (الغلط بيلع نفسه والنتيجة هي الافتراضي المكتوب جوه الكود). والمتغيّر اللي بتقرأه الصفحة الرئيسية وباب الإعدادات عام للمتصفح **مش مضبوط على النشر خالص** — فالصفحة الرئيسية و«الغرف» و«من نحن» و«ابدأ» و«تواصل معنا»: **صفر رابط واتساب** للزائر.
  - **اللي بيظهر للزائر النهارده على الرابط المنشور:** صفحة الأثاث فيها **18 زرار «اطلب عرض سعر فوري»** كلها بتفتح واتساب على رقم بينتهي في 2345 — ده **غير** الرقم المسجّل في سجل الشركة، ومكتوب بصيغة محلية من غير كود الدولة، فواتساب ما بيفتحش محادثة أصلاً من أغلب الأجهزة.
  - **القرار مش بتاعي:** الرقم اللي يشوفه الزبون كلمة المالك. مفيش وكيل يقلب رقم ظاهر للعملاء من تلقا نفسه — السؤال اتسأل: الرقم الصح هو اللي في سجل الشركة (بينتهي 9584) ولا اللي الموقع عارضه (بينتهي 2345)؟
  - **اللي هيتعمل بعد الإجابة:** منبع واحد يقرأ منه كل سطح، ومكان واحد يتغيّر فيه الرقم، وبناء رابط واتساب بكود الدولة، والصفحة الرئيسية تحمل الرابط زي باقي الصفحات.
  - **البوابات:** مفيش — دي لافة حصر، ولا سطر كود اتغيّر فيها.
`);

appendFileSync(ledgerPath, addition, "utf8");
const text = readFileSync(ledgerPath, "utf8");
console.log(`written=${text.includes(MARK)} · ledger lines=${text.split("\n").length}`);
