import { appendFileSync, readFileSync } from "node:fs";

const LEDGER = "docs/ledger/council-minutes.md";
const ar = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x660 + Number(d)));

const raw = `

- **المالك (2026-10-19 16:10):** **كود التحقق اتقفل بأمره الصريح — الداشبورد بيفتح بالإيميل وكلمة السر بس.** تليفونه ضاع، وهو ما بيشوف اللوحة من غيره، فالباب التاني بقى هو القفل مش الحارس. القرار قراره، ده بيتسجل عشان أي وكيل بعد كده ما يصلحش ده وهو فاكره عيب أمان.
  - **اللي اتعمل:** الباب بيسأل سجل الإعدادات ([[admin_gate_2fa_required]]) مش الكود — يعني الرجوع كلمة واحدة مش شغل كود. **ولا حاجة اتمسحت:** باب التحقق، ومفتاح المفتّش، وباب الظبط، والحارس اللي بيمنع أي باب عام يلمس لوحة الإدارة — كله في مكانه. لمّا السطر مش موجود أو السجل ما ردّش، **الباب بيفضل يطلب الكود** (الافتراضي الآمن ساير).
  - **الفرق اللي اتعمل في الباب:** لمّا الأمر يقول «مفيش كود»، الباب بيخلّي الجلسة قائمة بدل ما يقفلها، وبيسجّل في دفتر الجلسات إن الدخول ده **بلا تحقق** ([[is_2fa_verified: false]]) — مش بيمثّل إنه متحقق. وبيبتعث تنبيه على تليجرام بكل دخول بكلمة السر وحدها، والمسار ده محروس باختبار.
  - **مقاس حيّ على الرابط المنشور (عرض 390 بكسل، صورة اتبصّ عليها):** \`scratch/prove-gate-password-only.mjs\` — **7 من 7**: كتب إيميل وكلمة سر → نزل على اللوحة على طول و**مفيش خانة كود خالص** (صفر) · الشاشة قالت «لوحة التحكم» والقوائم كلها موجودة · **كلمة سر غلط لسه بترفض 401** — القفل مش اتحوّل لباب مفتوح · الجلسة اتسجلت في الدفتر بأنها بلا تحقق · أثر المحاجة اتمسح وفاضل **0** · صفر رسالة خطأ في المتصفح.
  - **البوابات:** 2,234 اختبار أخضر (7 حراس جدد للباب ده) · تيبشك سليم · بناء كامل · منشور · قياس حيّ فوق. **اللي ما اتقاسش:** تسليم التنبيه على تليجرام فعليًا (محروس باختبار وباب بيبعت، مش بتسليم مقاس على تليفونه).
`;

const text = ar(raw).replace(/\[\[([^\]]+)\]\]/g, "`$1`");
const outside = text.replace(/`[^`]*`/g, "");
const latin = [...new Set(outside.match(/[A-Za-z]{2,}/g) ?? [])];
if (latin.length) {
  console.error("مرفوض: لاتيني بره كود:", latin.slice(0, 10).join(", "));
  process.exit(1);
}
if (/[一-鿿]/.test(text)) {
  console.error("مرفوض: حرف صيني تسرّب");
  process.exit(1);
}
const before = readFileSync(LEDGER, "utf8");
appendFileSync(LEDGER, text);
const added = readFileSync(LEDGER, "utf8").slice(before.length);
console.log(`السجل: +${added.trimEnd().split("\n").length} سطر · أرقام عربية: ${/[٠-٩]/.test(added)}`);
