import fs from "node:fs";

/**
 * Records the digits atom in the repository ledger. Numerals are generated; the script refuses to
 * write while a Latin digit survives, and it names the measurement mistake that nearly cost an hour.
 */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **أرقام العميل بكتابه هو: 35 سلسلة لاتينية الأرقام صارت صفر، والحصر اتوسع لـ 14 عنوان.**`,
  "  - **الحصر الموسّع:** المشي محطة محطة على 14 عنوان من شاشات العميل لقى 35 سلسلة تحمل أرقام لاتينية (أسعار الكتالوج 18 · شرائح الميزانية 4 · عدّاد الخطوات · عدّاد الصور 12 · عدّاد الدفعات وسطر «كم دفعة فاضلة» · رقم السنة في الفوتر) — وفضلا عن كده لقى صفحة الغرفة اللي بتفتح من قايمة الغرف بتقول اسم الماركة باللاتيني جوه سؤال عربي، وسطر الفوتر بالإنجليزي على كل صفحة.",
  "  - **الإصلاح:** مساعد واحد «أرقام عربية» في ملف العربية بيحوّل الرقم رقم رقم وما بيعيدش تشكيل الآلاف — عشان ذيل التليفون ما يرجعش مفصول بفاصلة ألوف. اتوصّل بمحل العرض: كارت الأثاث، صفحة البداية، كراسة الطلب (التسميات والخطوات)، صفحة الغرفة وشريط الصور والمعرض المكبّر، والفوتر. وسؤال غرفة الغرف بقى بـ«أزينث ليفينج» زي باقي الصفحة، والماركة اللاتينية فضلت في بيانات البحث المشفّرة وفي فتات التنقل زي ما هي.",
  "  - **غلطة الآلة عندي (لازم تتسجّل):** أول قياس بعد التعديل قال إن الأرقام لسه لاتينية. السبب إن سيرفر المعاينة المحلي كان لسه شاغل على نفس البورت والسيرفر الجديد فشل في التثبيت — فالقياس اتعمل على نسخة قديمة. القاعدة الجديدة: قبل أي قياس محلي يتأكد إن السيرفر الجديد ثبت فعلاً وإن الصفحة بتطبع علامة النسخة الحديثة.",
  "  - **البوابات:** 1754 اختبار أخضر (منها 3 حالات جديدة على المساعد) · تيبشك سليم · بناء كامل · قياس حيّ على المنشور بعد النشر: 12 عنوان من 14 صفر كلمة وصفر رقم · العنوانان الفاضلين متسجلين: نموذج التأهيل المتميز (23 سلسلة إنجليزي — خاصية اللغة توصله وما تُقرأش) وصفحة ظهور في البحث (سلسلة واحدة).",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2);
