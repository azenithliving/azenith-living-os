const tally = { [V]: 0, [B]: 0, [N]: 0 };
let n = 0;
const body = [];
for (const g of groups) {
  if (!Array.isArray(g.items) || g.items.length === 0) throw new Error(`group ${g.title} has no items`);
  body.push("", `## ${g.title}`, "");
  for (const [item, status, proof] of g.items) {
    if (![V, B, N].includes(status)) throw new Error(`unknown status "${status}" on ${item}`);
    n += 1;
    tally[status] += 1;
    body.push(`${n}. **${item}** — *${status}* — ${proof}`);
  }
}

