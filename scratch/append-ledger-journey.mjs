import fs from "node:fs";

/** Records the sequenced customer-journey atom in the repository ledger. Numerals are generated. */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => String(s).replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **الرحلة مشت من أولها لآخرها: 11 محطة ثبتت، وصفر محطة واقفة.**`,
  "  - **المشي:** دخول بأربع اختيارات → بوابة العميل في صفحة الطلب → ورقة مصوّرة من غير دخول → عنوان سرّي → فتح الجواز → مقاسات هو اللي كتبها والقفل نزل (مقاسان مخزّنون، ختم 18:36:50 ز) → تلات ألوان والرابع يقفل → تصويت اتنين على نفس الرابط → نبضة على الورقة (18:37:52 ز) → الملف الذهبي عند المالك لاقى العميل وزرار «اتصل بيه» → صفر خطأ كونسول في الرحلة كلها.",
  "  - **تلات عيوب طلعت وهي بتمشي، واتصلحت:** (1) شاشة المقاسات كانت بتطلب منه يكتب من غير ما تكون عاملة مقابض تعرفها الآلة — اتقفلت. (2) أول رسالة في محادثة جديدة كانت بتسأل المخزن عن محادثة ما وصلهاش، فكل زبون بيفتح الشات بيولّد خطأ 404 فيصفحته — الباب كان صح والسؤال كان غلط، فاتصلح بعلَم «المخزن عرف الجلسة». (3) الأخطر: عميل له ورقة مقفلة وتصويت ونبضة كان «مفيش حد بهالحرف» في الملف الذهبي، لأن الدفتر كان بيعدّ سبع مساحات والورقة ما كانتش واحدة منها — بقت المصدر الثامن، واللي مفتاحه ملوش وسيلة تواصل يفضل مجهول بدل ما يتخمن.",
  "  - **اختبار أخضر كان كداب عند نفسي:** محطة الملف كانت بتقرا نص الصفحة كلها، فعدّت خضراء والعميل مش موجود — الصورة فضحته. القراءة بقت محصورة في لوحة الملف نفسها، والرقم اللي بيطلع دلوقتي من نص اللوحة (1143 حرف، الصوّتين ظاهرين).",
  "  - **البوابات:** 1769 اختبار أخضر · تيبشك سليم · بناء كامل · ثلاث نشرات على الرابط المنشور، والرحلة اتعادت بعد كل واحدة.",
  "  - **عيبين بان في الصورة واتسجلوا:** شاشة المالك بتعرض الموبايل بغير الصفر الأول (1099999991) يعني مش قابل للطلب زي ما هو مكتوب · وكلمة إنجليزي جوه عربي في محادثة مدير المبيعات («Traffic» و«To») رغم طبقة الصوت العربي.",
  "  - **البند في القائمة الجامعة:** الرحلة الكاملة كانت «مش مبنية» لعدم وجود تشغيل متسلسل مُثبت — النهاردة عنده تشغيل متسلسل مُثبت بكل محطاته.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
