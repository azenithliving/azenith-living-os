import fs from "node:fs";

/** Records the deletion the owner ordered, with the row preserved first. Numerals are generated. */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => String(s).replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const STALE = "سؤال: مكان الشركة فين ومواعيد الشغل ايه الإجابة: الشركة فى مدينة السلام - القاهرة ،ومواعيد العمل يوميا من 10 صباحا حتى 6 مساء عدا يوم الجمعة";

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **بكلمة «امحيه»: السطر القديم اتمحى، والعنوان اتقذ في سطر لوحده.**`,
  "  - **اللي كان في السجل قبل المحو (محفوظ حرفياً هنا للرجوع):** «" + STALE + "» — بتاريخ 2026-04-20.",
  "  - **اللي اتعمل وبالترتيب:** أول اتأكدت إن العنوان مش مسجّل في أي حتة تانية (جدول الشركات فيه الاسم والدومين والواتساب بس، ومفيش عمود عنوان) · بعدين اتكتب سطر جديد: «عنوان الدار: مدينة السلام - القاهرة. (الشغل بالطلب والتفصيل، ملناش معرض تستناه)» · وبعدها تم المحو بالمفتاح نفسه بعد ما اتقرا تاني إن نفس الصفحة لسه تحمل الجملة القديمة (لو كانت اتغيّرت، كان وقف) · والقراية الراجعة من المخزن: صفّين بس — سطر العنوان الجديد وسطر «مواعيد العمل: كل أيام الأسبوع من ٩ صباحًا حتى ٨ مساءً، ما عدا الجمعة».",
  "  - **ملاحظة على الآلة نفسها:** ردّ المحو رجع عدد الصفوف الممحاة فاضي، فالاعتماد كان على القراية الراجعة من المخزن مش على الرد — وده أصح في عملية محو.",
  "  - **وصول العنوان:** باب المسترشد بيبنّي نظامه من كل أسطر السجل، فالسطر الجديد بقى مقروء له من غير ما أوصّل حاجة.",
  "  - **اللي يفضل مفتوح:** مفيش لسه شاشة إدارية بتعرض عنوان الدار، وقارئ المواعيد بيقرا السطر الأحدث فقط — لو كتبته سطر تاني بنفس البداية يتقدّم عليه. وده مقصود: السجل هو صاحب الكلمة.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2);
