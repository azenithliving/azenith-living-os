import fs from "node:fs";

/** Records the sealing decision for the paper desk. Numerals generated, never typed. */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **قرار الورقة المرفوضة: مين الشاهد اللي يقدر يقفل الورقة لما السحابة ترفض.**`,
  "  - **الحقيقة المقاسة:** محرك القراءة على الجهاز ما كملش جوه الطلب ولا مرة في ١٧ قراءة محفوظة — ف توصيله داخل الطلب مش حل، ده طريق متقاس ومجرّب. والقارئ السحابي بيرفض النهارده من النشر، فالورقة بتفضل صفر رقم والعميل ما يقدرش يقفلها.",
  "  - **القرار:** لما القارئ السحابي يرفض، الأرقام اللي العميل كاتبها بنفسه تبقى هي الشاهد — تتقفل الورقة بيها، والسطر قدام المالك يقول «من كلام العميل — القارئ الذكي كان مرفوض»، مش «الشاهدين اتفقوا». ده مش اختراع رقم: ده رقم صاحب البيت نفسه، والفرق بيتقال في المصدر مش بيتخبّى.",
  "  - **اللي مش هيتعمل:** ما حدش يوصّل محرك الجهاز جوه الطلب تاني — اتقاس ولأ. الشغلانة دي لو اتعملت تكون بعد الحفظ (مهمة خلفية أو الوردية اليومية)، مش في نفس الثانية اللي العميل مستني فيها.",
  "  - **الخطوة الجاية:** تعديل باب التأكيد يقبل رقم العميل لما الصفّة مرفوضة، مع حارس يمنع إن نفس السطر يدّعي اتفاق شاهدين، وقياس حيّ على ورقة حقيقية.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2);
