const AI = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **نموذج التأهيل ردّ على العميل العربي بلغته: 23 سلسلة إنجليزي بقت صفر.**`,
  "  - **السبب الجذري، مقاس قبل الإصلاح:** النموذج كان بياخد خاصية اللغة منصفحته وبتوصله فعلًا — وما بيقرأهاش خالص (سطر واحد في الملف بيستقبلها ولا تُستخدم). فالعميل اللي داخل من صفحة عربية كان بيرجع إنجليزي من أول خطوة.",
  "  - **اللي كان بيحصل كمان في الملخص:** كان بيطبع المفاتيح المخزّنة نفسها للعميل («100k-200k») وفئة التقييم الداخلية (Silver/Diamond) — يعني آلة جوه كلامه، وده ممنوع عندك حتى لو بالإنجليزي.",
  "  - **الإصلاح:** أسماء الغرف بقى ليها صاحب واحد في كتالوج الغرف (الاسم الإنجليزي يفضل هو القيمة اللي بتتخزن وتتحسب، والعربي للعرض بس) · خيارات التوقيت اتكتبلها نصف عربي في مصدرها · تسمية نطاق الاستثمار بتتحول لأرقامه وقت العرض · جملة «ه نرجع طلبك» بقت بعربيته وساعته · الصفحة بقت بتفتح على لغة المتجر (عربي) بدل ما تستنى متصفح الزبون، ومفتاح اللغة بيكتب رجوع في نفس المكان · وسطر «دليل أزينث» في صفحة الظهور في البحث.",
  "  - **الحارس:** ملف اختبار جديد بيفشل لو اتضافت مساحة أو توقيت من غير اسم عربي، وبيأكد إن جملة الموعد ما بتطالعش حرف لاتيني — وهي نفس العلة اللي ولّدت العيب.",
  "  - **البوابات:** 1758 اختبار أخضر · تيبشك سليم · بناء كامل · قياس حيّ على المنشور بعد النشر: 13 عنوان من شاشات العميل، كلها صفر كلمة لاتينية وصفر رقم لاتيني، وصفر خطأ كونسول، وصورة الشاشة مقروءة بعربيته.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
