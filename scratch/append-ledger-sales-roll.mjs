import fs from "node:fs";

/**
 * Records the sales-roll atoms: the silent refusal that now speaks, the tally that found a screen,
 * and the English that tried to ride in with it. Numerals are generated.
 *   node scratch/append-ledger-sales-roll.mjs
 */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **شاشة المبيعات بقى عندها لسان: الرفض بيتقال، والرقم بقى له مكان، والإنجليزي مابقيش يركب معاه.**`,
  "  - **الأول: الرفض كان بيبلع نفسه.** الباب كان بيردّ بسطرين مفاتيحهم «leads, totals»، والفورمة كانت بتعمل «لو الرد تمام خد القائمة» من غير أي فرع تاني — يعني ردّ الباب برفض أو قطع الاتصال كان بيروح لسطر واحد في طرفية المتصفح، والشاشة تعرض صفر وتسيب المالك قدامها. دلوقتي الرفض بيظهر فوق القائمة بنفسه، والأعداد القديمة بتتقال «آخر ما وصل» مش «مفيش عملاء»، ولما الباب يرجع التحذير بيختفي من نفسه.",
  "  - **التاني: الرقم الصحيح كان مقفول في الباب.** بعد ما اتصلّح تجميع الطراز (اللي فات) لقيناه مفيش شاشة بتطبعه. بقى تحت عنوان «العملاء المحتملين» سطر: «أكثر الطرازات المطلوبة: مودرن ٥ · كلاسيك ٢ (٧ سطر ما اتحسبش — اسمه مش طراز)». والعدد ده بتاع الدفتر (كل سطر عميل في الدفتر)، مش بتاع باب التحليلات (سطور الزوار في آخر تلاتين يوم = مودرن ٦ · كلاسيك ٤ · ١٤ مرفوض) — نفس المقياس، مجموعتين مختلفتين، وده مكتوب هنا عشان محدش يقارن الرقمين ويقول فيهم غلط.",
  "  - **التالت: الإنجليزية اللي حاولت تركب.** أول صورة حية للتحذير طلعت «القائمة ما جابتش رد: Failed to fetch» — إحنا بنقول الحقيقة بس بكلمة الآلة في نص كلامه. بقى لقطع الاتصال جملته هو: «القائمة ما جابتش رد — الاتصال بالباب وقّع من غير ما يوصّل»، ورقم الحالة بيتكتب بأرقامه.",
  "  - **البوابات:** 1875 اختبار أخضر · تيبشك سليم · بناء كامل · صفر خطأ كونسول في القياس الحيّ.",
  "  - **الدليل الحيّ على الرابط المنشور (عرض ٣٩٠، داخل بحسابك على شاشة المبيعات، تلات حالات):** الباب بردّ → مفيش تحذير · السطر موجود بأرقام عربية · الباب يتقطع (اتمنى) → التحذير بيظهر · الباب يرجع → التحذير يختفي. والصورة اتبصّيت عليها.",
  "  - **ملاحظة على أثر القياس:** القطع كان متعمّد في الآلة وبس (قفلنا النداء في المتصفح) — مفيش سطر اتحذف ولا اتغيّر في المخزن.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r));
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2, "lines");
