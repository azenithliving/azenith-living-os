import { appendFileSync, readFileSync } from "node:fs";

/**
 * The minute for the write-boundary round — and the correction of what I told the owner before
 * measuring it.
 */
const ar = (text) => text.replace(/[0-9]/g, (d) => String.fromCharCode(0x660 + Number(d)));
const MARKER = "الدليل إن الموديل بيتعلم فعلاً";

const ledger = readFileSync("docs/ledger/council-minutes.md", "utf8");
if (ledger.includes(MARKER)) {
  console.log("already recorded — nothing written");
  process.exit(0);
}

const now = new Date();
const stamp = ar(
  `${now.getUTCFullYear()}-${String(now.getUTCMonth() + 1).padStart(2, "0")}-${String(now.getUTCDate()).padStart(2, "0")} ${String(now.getUTCHours()).padStart(2, "0")}:${String(now.getUTCMinutes()).padStart(2, "0")}`,
);

const minutes = ar(`

- **وكيل المتجر (${stamp}):** **الدليل إن الموديل بيتعلم فعلاً: 26٪ من صفوف الموظفين كانت جُملة إنجليزي، بقت 5٪ — وده بيصحّح اللي قاله الوكيل للمالك قبل ما يقيس.**
  - **اللي اتقال قبل القياس:** «الموظفون بيفتكروا بالإنجليزي، هخليهم يكتبوا عربي من المصدر». **القياس كذّب المقدمة:** القانون ده موجود أصلاً من ٢٦ سبتمبر في وحدة قواعد خطاب المالك (سطر «اكتب بالعربية المصرية فقط… ممنوع كلمة إنجليزية في وسط الجملة العربية»).
  - **القياس على القاعدة نفسها:** صفوف الموظفين اللي فيها ثلاث كلمات إنجليزي ورا بعض — في آخر ٧ أيام: **١ من ٢٠** · قبل كده: **٢٢٥ من ٨٥٠ (٢٦٪)**. يعني القانون شغال، واللي بيفضل على شاشته من ده **تاريخ مكتوب قبل القانون**، مش كتاب جديد.
  - **اللي اتعمل بعد ما اتعرف ده:** ثلاث مواضع بتخزّن كلام موظف بقت بتنطق الصف **وقت ما تكتبه** (ردّ السرب في المُنسّق · جولة الصباح على تليجرام والمحادثة · صف الترحيب في محادثة جماعية) — فالقديم يفضل زي ما هو بس التاريخ الجديد ما بيكبرش. صف المالك نفسه **متلمّش** عن عمد: كلامه هو، وتعديلّه تصحيح للشخص الوحيد اللي الدار بيشتغل له.
  - **اللي يخلي ده آمن:** اختبار اتكتب الأول على الجُمل المقاسة على شاشته نفسه — إن نطق الصف مرتين (مرة وقت الكتابة ومرة وقت القراءة) بيرجع نفس النص بالحرف، وعنوان الويب بيمشي سليم من الاتنين. من غير الإثبات ده كان ممكن التمريرين ياكلوا بعض.
  - **اللي ما اتعملش، ولأجل إيه:** 850 صف قديم ما اتعدّلتش — دي سجلات تاريخها مكتوب، وتعديلها كلمة المالك مش كلمة وكيل · وما لفّيتش قانون الخطاب على البرومبتات اللي تردّ JSON (موجّه المهام ومصنّف النوايا) — القانون عن كلام يقرأه هو، وحشره في برومبت آلة بيزود دوشة على الصغير.
  - **البوابات:** 2037 اختبار أخضر (+6: 2 على الأمان إن النطق مش بياكل نفسه، 3 على المواضع التلاتة، و1 إن صف المالك بيفضل زي ما كتبه) · تيبشك سليم · بناء كامل · منشور على الرابط.
`);

appendFileSync("docs/ledger/council-minutes.md", minutes, "utf8");
const after = readFileSync("docs/ledger/council-minutes.md", "utf8");
console.log(`written: ${after.includes(MARKER)} · file lines: ${after.split(/\r?\n/).length}`);
