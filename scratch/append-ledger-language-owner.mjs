import fs from "node:fs";

/**
 * Records the one-owner language atom in the repository ledger. Numerals are generated.
 *   node scratch/append-ledger-language-owner.mjs
 */
const when = new Date().toISOString().slice(0, 16).replace("T", " ");
const AI = (s) => s.replace(/[0-9]/g, (d) => String.fromCodePoint(0x0660 + Number(d)));

const lines = [
  "",
  `- **وكيل المتجر (${when}):** **لغة العميل بقى ليها صاحب واحد — الضبط العام، والشاشتين بيطيعوه.**`,
  "  - **العيب، مقاس من الكود ومن الصفحة مع بعض:** شاشة «مسار النخبة» كانت بتاخد نسخة خاصة بيها من اللغة أول ما تفتح، وبعدين بتخمن من المتصفح، والرابط «?lang=en» كان بيحرّك نسختها هي بس. والحارس اللي على الهيدر بيكتب في الضبط العام — يعني الضبط والصفحة والرابط والمتصفح أربع أصوات على نفس الحقيقة، والصفحة هي اللي بتكسب في كل مرة. والدليل التاني طلع من البناء: لما اختار الإنجليزي، الكلام اتغير للإنجليزي بس الصفحة فضلت واقفة من اليمين للشمال، لأن الكلاس «rtl/ltr» في Tailwind هو شرط تنسيق مش تنسيق نفسه.",
  "  - **اللي اتعمل:** مقياس واحد اسمه «الضبط العام» قرّاه الشاشتين. التخمين من المتصفح اتشال خالص — أرضية المتجر عربي للسوق المصري من الأصل، فالتخمين ما بيضيفش حاجة غير إنه يقلب على العميل. والرابط بقى بيكتب في الضبط نفسه مش في نسخة الصفحة، فباقي الموقع بيطاوعه. وزرار اللغة جوه الشاشة بقى كاتب واحد للضبط. وسطر الاتجاه بقى على العنصر اللي بيشيل الصفحة. وكمان سطر «الاستخبارات المتميزة» اتشال — دي ترجمة حرفية لاسم الشاشة بتقول «جهاز مخابرات» على براند أثاث، واتكتب «أزينث — تجربة النخبة» زي صفحة الكراسة.",
  "  - **البوابات:** 1862 اختبار أخضر · تيبشك سليم · بناء كامل · صفر خطأ كونسول وقت القياس.",
  "  - **الدليل (على بناء كامل شغّال عندي على المنفذ 3717 — مش على الرابط المنشور، وده الفرق):** تلات مسارات مشيت بمتصفح حقيقي بعرض 390: زائر جديد بمتصفح عربي → الشاشتين بالعربي والاتجاه يمين-شمال · الرابط قال إنجليزي في الكراسة → المسار طاوعها واتجهه شمال-يمين (قبل الإصلاح كان بيرجع عربي من رأسه) · زرار اللغة اتضغط في المسار → المسار اتغير والكراسة لقته متغير كمان. صور المسارين اتبصّيت عليها.",
  "  - **اللي معلّق:** التعديلين دول (نسخة اللغة + اتجاه الصفحة) محفوظين على الفرع المحلي بس، والنشر مستني أداة الأوامر في الجلسة دي تقع وترجع — الدفع لبره من البيئة البديلة مابيقدرش يفتح قناة على الموقع. فالبوابة الرابعة على الرابط المنشور لسه ما اتعملتش، ومحدش يقول «اتنشر» قبلها.",
  "",
];

const body = AI(lines.join("\n"));
const strays = (body.match(/[0-9]+/g) ?? []).filter((r) => !when.includes(r) && r !== "3717");
if (strays.length) throw new Error(`Latin digits left: ${strays.join(", ")}`);
fs.appendFileSync("docs/ledger/council-minutes.md", body, "utf8");
console.log("appended:", lines.length - 2, "lines");
