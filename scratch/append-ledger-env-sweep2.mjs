import { appendFileSync } from "node:fs";

/** The second sweep word: the old config copies left the project. Names and counts only. */
const ar = (text) => text.replace(/[0-9]/g, (d) => String.fromCharCode(0x660 + Number(d)));
const now = new Date();
const stamp = ar(
  `${now.getUTCFullYear()}-${String(now.getUTCMonth() + 1).padStart(2, "0")}-${String(now.getUTCDate())
    .padStart(2, "0")} ${String(now.getUTCHours()).padStart(2, "0")}:${String(now.getUTCMinutes()).padStart(2, "0")}`
);

const minute = `

- **وكيل المتجر (${stamp}):** **الكلمة التانية في التطهير: ١٧ نسخة قديمة من ملفات الضبط خرجت من المشروع، والأربعة مسحت من ٤ ملفات لسه شغالين.**
  - **الجرد قبل القرار:** ٢٤ ملف ضبط في جذر المشروع. سبعة منهم بيقرأهم سكربت أو المتجر نفسه (\`.env.local\` · \`.env\` · مثالَّين · وتلات ملفات بتستخدمهم أدوات مزامنة الضبط على المنصة) — والـ١٧ الباقيين نسخ احتياط من ٢٩ يوليو و٠ و٢٤ سبتمبر، ولا ملف في المتجر بيقرا واحد فيهم.
  - **اللي اتعمل:** السبعة اللي ليهم لازمة فضلوا في مكانهم، بس اتشال منهم سطور الأربعة اعتماد اللي المالك أمر بيها. والـ١٧ طلعوا بره المستودع لأرشيف المالك، بعد ما اتنظفوا من نفس السطور — فالمجموع: ٥٩ سطر اعتماد خرج، وصفر ملف في المشروع فيه واحد من الأربعة. الملف الحيّ لسه بـ١٠٠ اسم، والباقي زي ما هو.
  - **ليه الأرشيف مش المزبلة:** المالك أمر بالمسح، بس البروتوكول عنده إن الحاجة تتنقل لأرشيفه الأول وتمحى فعليًا بكلمة صريحة. فالنسخ اتحوّت بره المشروع من غير ما تتفنى من على القرص — ولو قال «امحيها فعليًا» تتمسح من الأرشيف في ثانية.
  - **البوابات بعد التطهير:** ١٩٢ اختبار أخضر · بناء كامل · مفيش نشر (ملفات محلية مش داخل چيت، \`.gitignore\` بيشمل \`.env*\`).
  - **اللي يفضل مفتوح من نفس الجذر:** القيم اللي على المنصة نفسها (فيرسل) — الأربعة دول ممكن يكونوا متسجلين هناك، ودي شاشة ما بتقراش من هنا. ولو أي واحد منهم كان بيتقال إنه حيّ، الأحسن يتعمله دوران (rotation) مش مسح من ملفنا بس.
`;

appendFileSync("docs/ledger/council-minutes.md", ar(minute), "utf8");
console.log("appended");
