-- 20261015_b_customer_memory.sql
--
-- The customer's own memory, kept under the key the roll already uses for him.
--
-- Measured 2026-10-15 by scratch/census-customer-memory.mjs, and the answer was not «built without
-- proof» — it was «never stored a thing»:
--   · `user_preferences` exists as (user_id, preferences) while `lib/ultimate-agent/memory-store.ts`
--     writes (category, key, value, confidence, source, last_confirmed) — six columns the table never
--     had — so every write was refused with 42703, the refusal was swallowed in a `catch` that only
--     printed to the console, and the table held 0 rows since the day it was created;
--   · what the store does know about a customer lives in `consultant_sessions.insights` and
--     `room_sketches`, keyed by the SESSION or by one paper: 150 sessions, only 2 carrying a style, a
--     budget or an area, 0 carrying his phone — so his taste dies with the tab, and a man who comes
--     back next week is a stranger again;
--   · the swarm's vector memory (`ops_semantic_memory`) holds 0 rows behind a reader that runs on every
--     admin chat reply, which is a different atom and is NOT what this table is for.
--
-- The shape: one row per fact he himself gave, under `customer_key` — the roll's own key
-- (`phone:<national digits>`, formed only by `lib/customers/identity.ts`, never guessed from a photo).
-- Text, not vectors: the store must remember him with zero model keys, and an embedding is an addition
-- that can come later on top of the same rows.
--
-- `evidence` is not decoration: it is the sentence or the paper the fact came from, so the shop can say
-- «من ورقتك» instead of asserting a taste nobody recorded.
--
-- Locked like everything else in this database since 2026-10-15: row level security on, no policy, so
-- the public browser key reads nothing and only the store's own credential writes.

--SPLIT--

create table if not exists public.customer_memory (
  id            bigint generated by default as identity primary key,
  company_id    uuid    not null references public.companies (id) on delete cascade,
  customer_key  text    not null,
  kind          text    not null check (kind in ('style', 'colour', 'area', 'room', 'budget', 'note')),
  value         text    not null,
  source        text    not null,
  evidence      text,
  first_seen_at timestamptz not null default timezone('utc', now()),
  last_seen_at  timestamptz not null default timezone('utc', now()),
  constraint customer_memory_one_fact_per_customer unique (company_id, customer_key, kind, value),
  constraint customer_memory_key_shape check (customer_key ~ '^(phone:[0-9]{9,15}|email:[^@]+@[^@]+|name:.+)$')
);

--SPLIT--

create index if not exists idx_customer_memory_customer
  on public.customer_memory (customer_key, last_seen_at desc);
create index if not exists idx_customer_memory_kind
  on public.customer_memory (company_id, kind);

--SPLIT--

alter table public.customer_memory enable row level security;
